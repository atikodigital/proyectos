export function getIdioma() {
  let i = '';
  try { i = localStorage.getItem('hash_idioma') || ''; } catch (e) { /* sin storage */ }
  if (!DICT[i]) {
    let nav = '';
    try { nav = (navigator.language || '').slice(0, 2).toLowerCase(); } catch (e) { /* sin navigator */ }
    i = DICT[nav] ? nav : 'es';
  }
  return i;
}

export function t(key) {
  const i = getIdioma();
  return (DICT[i] && DICT[i][key]) || DICT.es[key] || key;
}

